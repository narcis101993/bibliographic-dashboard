#!/usr/bin/env python3
"""Build dashboard/vendor/chart.min.js — a trimmed Chart.js bundle.

Bundles scripts/chart-entry.js (bar + doughnut controllers/elements,
category + linear scales, tooltip + legend; Chart.js 4.4.7, MIT) with
esbuild into a single browser-global script, replacing the stock
chart.umd.min.js which also shipped unused line/pie/polar/radar/
scatter/bubble controllers, logarithmic scales, decimation, filler
and title plugin (Lighthouse: "Reduce unused JavaScript").

Usage:
    python3 scripts/build_chart_bundle.py            # uses node_modules/.bin/esbuild or npx esbuild@0.25.10

 Requires the devDependencies in package.json (`npm install`); falls back
to `npx --yes esbuild@0.25.10` (Chart.js itself is imported from
node_modules, so `npm install` is still needed for chart.js).
"""
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENTRY = ROOT / "scripts" / "chart-entry.js"
OUT = ROOT / "dashboard" / "vendor" / "chart.min.js"
BANNER = (
    "/* Chart.js 4.4.7 (MIT, see vendor/CHARTJS-LICENSE.md) — custom bundle: "
    "bar + doughnut only. Generated by scripts/build_chart_bundle.py; "
    "do not edit by hand. */"
)


def main() -> int:
    local = ROOT / "node_modules" / ".bin" / "esbuild"
    if local.exists():
        cmd = [str(local)]
    else:
        npx = shutil.which("npx")
        if not npx:
            print("ERROR: esbuild not found. Run `npm install` first.", file=sys.stderr)
            return 1
        cmd = [npx, "--yes", "esbuild@0.25.10"]
    cmd += [
        str(ENTRY),
        "--bundle",
        "--minify",
        "--format=iife",
        "--target=es2019",
        f"--banner:js={BANNER}",
        f"--outfile={OUT}",
    ]
    print("+", " ".join(cmd))
    result = subprocess.run(cmd, cwd=ROOT, check=False)
    if result.returncode != 0:
        print("ERROR: esbuild failed", file=sys.stderr)
        return result.returncode
    size = OUT.stat().st_size
    print(f"Wrote {OUT.relative_to(ROOT)} ({size / 1024:.1f} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
